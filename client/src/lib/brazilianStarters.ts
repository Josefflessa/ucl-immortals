// A página da fonte ordena os jogadores principais por relevância, mas não
// entrega um overall pronto para o nosso modelo. Usamos essa ordem, a força
// média do clube e um pequeno degrau por posição na lista para evitar blocos
// artificiais de notas repetidas.
const CLUB_STRENGTH: Record<string, number> = {
  Botafogo: 78, Ceará: 70, Vasco: 75, 'Atlético Mineiro': 79,
  Flamengo: 82, Cruzeiro: 78, Bahia: 76, Juventude: 70, Vitória: 70,
  Fluminense: 77, Fortaleza: 75, Grêmio: 76, Mirassol: 70,
  Bragantino: 73, Santos: 78, 'São Paulo': 78, Palmeiras: 82,
  Corinthians: 77, Sport: 69, Internacional: 76,
};

const rebalanceClamp = (value: number) => Math.max(30, Math.min(95, Math.round(value)));
const rankByClub = new Map<string, number>();

export const BRAZILIAN_STARTERS: Player[] = BRAZILIAN_STARTERS_BASE.map(player => {
  const rank = rankByClub.get(player.club) ?? 0;
  rankByClub.set(player.club, rank + 1);
  const targetOverall = Math.max(
    64,
    Math.min(87, Math.round((CLUB_STRENGTH[player.club] ?? 72) + 3 - rank * 1.35)),
  );
  const delta = targetOverall - player.overall;
  return {
    ...player,
    overall: targetOverall,
    pace: rebalanceClamp(player.pace + delta),
    shooting: rebalanceClamp(player.shooting + delta),
    passing: rebalanceClamp(player.passing + delta),
    dribbling: rebalanceClamp(player.dribbling + delta),
    defending: rebalanceClamp(player.defending + delta),
    physical: rebalanceClamp(player.physical + delta),
    composure: rebalanceClamp(player.composure + delta),
    vision: rebalanceClamp(player.vision + delta),
  };
});
